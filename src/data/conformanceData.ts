// ============================================================================
// Query & Lookup Utility Functions
// ============================================================================

/**
 * Retrieve all registered pathway categories (discovered and unavailable).
 */
export function getAllPathwayModels(): CanonicalPathwayModelMetadata[] {
  return CANONICAL_PATHWAY_MODELS;
}

/**
 * Retrieve only the 6 discovered pathway models that possess formal Petri nets.
 */
export function getDiscoveredPathwayModels(): CanonicalPathwayModelMetadata[] {
  return CANONICAL_PATHWAY_MODELS.filter((m) => m.isDiscovered && m.slug !== null);
}

/**
 * Get alignment quality metrics for a given pathway model slug.
 */
export function getAlignmentQualityBySlug(
  slug: string
): PathwayAlignmentQuality | undefined {
  return CANONICAL_ALIGNMENT_QUALITY.find((q) => q.modelSlug === slug);
}

/**
 * Get structural quality and soundness metrics for a given pathway model slug.
 */
export function getModelStructureQualityBySlug(
  slug: string
): ModelStructureQuality | undefined {
  return CANONICAL_MODEL_STRUCTURE_QUALITY.find((m) => m.modelSlug === slug);
}

/**
 * Get all deviation records for a given pathway model slug.
 */
export function getPathwayDeviationsBySlug(slug: string): PathwayAlignmentDeviation[] {
  return CANONICAL_ALIGNMENT_DEVIATIONS.filter((d) => d.modelSlug === slug);
}

/**
 * Get the top-level Category Summary deviation record for a model slug.
 */
export function getCategorySummaryDeviation(
  slug: string
): PathwayAlignmentDeviation | undefined {
  return CANONICAL_ALIGNMENT_DEVIATIONS.find(
    (d) => d.modelSlug === slug && d.scope === 'Category Summary'
  );
}

/**
 * Get the activity-level breakdown deviation records for a model slug.
 */
export function getActivityBreakdownDeviations(
  slug: string
): PathwayAlignmentDeviation[] {
  return CANONICAL_ALIGNMENT_DEVIATIONS.filter(
    (d) => d.modelSlug === slug && d.scope === 'Activity Breakdown'
  );
}
